export const STRINGS: Record<Lang, Strings> = { en, es };

export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("appealpath.lang");
    if (saved === "en" || saved === "es") return saved;
  } catch {
    // Private mode or blocked storage: fall through to the browser's language.
  }
  return navigator.language?.toLowerCase().startsWith("es") ? "es" : "en";
}

export function saveLang(lang: Lang) {
  try {
    localStorage.setItem("appealpath.lang", lang);
  } catch {
    // Not saving the choice is fine; the toggle still works for this visit.
  }
}
